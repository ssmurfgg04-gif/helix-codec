// Constraint verification
// ---------------------------------------------------------------------------

/**
 * Verify that a Yin-Yang encoded DNA sequence satisfies constraints.
 *
 * Checks:
 *   1. No homopolymers > 3 (inherent in YYC by design)
 *   2. GC content within [0.4, 0.6] (should be ~0.5 by design)
 *   3. All bases are valid {A, C, G, T}
 *
 * @param dna DNA string to verify
 * @returns Verification result
 */
export function yinyangVerifyConstraints(dna: string): {
  valid: boolean;
  maxHomopolymer: number;
  gcContent: number;
  invalidBases: number;
} {
  // Check for invalid bases
  let invalidBases = 0;
  for (let i = 0; i < dna.length; i++) {
    if (BASE_TO_IDX[dna[i]] === undefined) {
      invalidBases++;
    }
  }

  // Compute max homopolymer run
  let maxHomo = 1;
  let run = 1;
  for (let i = 1; i < dna.length; i++) {
    if (dna[i] === dna[i - 1]) {
      run++;
      if (run > maxHomo) maxHomo = run;
    } else {
      run = 1;
    }
  }

  // Compute GC content
  let gc = 0;
  for (let i = 0; i < dna.length; i++) {
    if (dna[i] === "G" || dna[i] === "C") gc++;
  }
  const gcFrac = dna.length > 0 ? gc / dna.length : 0;

  return {
    valid: invalidBases === 0 && maxHomo <= 3 && gcFrac >= 0.4 && gcFrac <= 0.6,
    maxHomopolymer: maxHomo,
    gcContent: gcFrac,
    invalidBases,
  };
}
